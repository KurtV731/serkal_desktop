"use strict";
const assert = require("node:assert/strict");
const {evaluate,validDate} = require("../2 src/common/season-policy");
const first = {episode_number:1,air_date:"2027-01-19"};
const partial = evaluate({episodes:[first]}, {episode_count:8});
assert.equal(partial.announcementOnly,true);
assert.equal(partial.episodeCount,8);
assert.equal(partial.announcedStart,"2027-01-19");
assert.deepEqual(partial.episodeDates,[]);
assert.equal(evaluate({episodes:[first]}).complete,false);
assert.equal(evaluate({},{}).seasonStart,"");
assert.equal(evaluate({},{}).placeholderStart,"");
assert.equal(evaluate({}, {air_date:"2027-01-19",episode_count:8}).announcedStart,"2027-01-19");
assert.equal(validDate("2027-02-29"),false);
assert.equal(validDate("2028-02-29"),true);
assert.equal(evaluate({episodes:[first,{episode_number:2,air_date:"2027-02-30"}]}).complete,false);
assert.equal(evaluate({episodes:[first,{...first}]}).complete,false);
assert.equal(evaluate({episodes:[first,{episode_number:3,air_date:"2027-01-26"}]}).complete,false);
const full = evaluate({episodes:[{episode_number:2,air_date:"2027-01-26"},first]}, {episode_count:2});
assert.equal(full.complete,true);
assert.deepEqual(full.episodeDates,["2027-01-19","2027-01-26"]);
assert.equal(evaluate({episodes:[first,{episode_number:2,air_date:first.air_date}]}).complete,true);
assert.equal(evaluate({episodes:[first,{episode_number:2,air_date:"2027-01-26"}]},{episode_count:8}).complete,false);
console.log("Season policy: incomplete, unknown, invalid, duplicate, reordered and confirmed simultaneous dates passed");
